-- ==========================================
-- 9. ATOMIC VIDEO VIEWS COUNTER
-- ==========================================

CREATE OR REPLACE FUNCTION public.increment_video_views(
    video_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    updated_views BIGINT;
BEGIN

    UPDATE public.videos
    SET views = COALESCE(views, 0) + 1
    WHERE id = video_id
    RETURNING views INTO updated_views;

    RETURN updated_views;

END;
$$;


GRANT EXECUTE
ON FUNCTION public.increment_video_views(BIGINT)
TO anon;


