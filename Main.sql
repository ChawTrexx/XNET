-- ==========================================
-- 7. COMMENTS POLICIES
-- ==========================================

CREATE POLICY "Public can read comments"
ON public.comments
FOR SELECT
TO anon
USING (true);


CREATE POLICY "Public can post comments"
ON public.comments
FOR INSERT
TO anon
WITH CHECK (
    length(trim(content)) > 0
    AND length(content) <= 200
    AND length(user_name) <= 50
);


GRANT SELECT, INSERT ON public.comments TO anon;


